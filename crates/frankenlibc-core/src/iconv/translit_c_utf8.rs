//! glibc's `iconv` `//TRANSLIT` results in a UTF-8 `LC_CTYPE` (C.UTF-8),
//! stored as the difference from the C-locale table in `translit_c`.
//!
//! Black-box capture, not a copy of glibc data, made the same way as
//! `translit_c`: every code point U+0080..U+10FFFF (minus surrogates and the
//! U+E0000..U+E007F tags) converted from UTF-8 to `ASCII//TRANSLIT` by glibc
