//! Bounded classic Secure RPC secret-key records.
//!
//! The encrypted half stores 48 hexadecimal key digits followed by a repeated
//! 16-digit prefix checksum, encrypted with password-derived DES CBC. A found
//! record with a failed checksum is a successful lookup with an empty secret,
//! distinct from an absent or malformed record.

use crate::crypt::des::{RpcDesError, rpc_des_hex_crypt};

use super::{PUBLICKEY_HEX_BYTES, secure_rpc_value};

pub const CHECKSUM_HEX_BYTES: usize = 16;
pub const ENCRYPTED_HEX_BYTES: usize = PUBLICKEY_HEX_BYTES + CHECKSUM_HEX_BYTES;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SecretKey {
    Key([u8; PUBLICKEY_HEX_BYTES]),
    WrongPassword,
}

/// Find the encrypted half without invoking an unbounded C-string decoder.
/// The first exact matching record owns the result, including malformed data.
pub fn lookup_encrypted_secret(
    content: &[u8],
    netname: &[u8],
) -> Option<[u8; ENCRYPTED_HEX_BYTES]> {
    let value = secure_rpc_value(content, netname)?;
    let separator = value.iter().position(|&byte| byte == b':')?;
    let public = &value[..separator];
    let encrypted = &value[separator + 1..];
    if public.len() != PUBLICKEY_HEX_BYTES
        || !public.iter().all(u8::is_ascii_hexdigit)
        || encrypted.len() != ENCRYPTED_HEX_BYTES
        || !encrypted.iter().all(u8::is_ascii_hexdigit)
    {
        return None;
    }
    encrypted.try_into().ok()
}

/// Decrypt a complete classic record and verify its repeated-prefix checksum.
/// No caller-owned output is touched, including on allocation failure.
pub fn decrypt_secret(
    encrypted: &[u8; ENCRYPTED_HEX_BYTES],
    password: &[u8],
) -> Result<SecretKey, RpcDesError> {
    let mut plaintext = *encrypted;
    rpc_des_hex_crypt(&mut plaintext, password, true)?;
    let mut difference = 0u8;
    for index in 0..CHECKSUM_HEX_BYTES {
        difference |= plaintext[index] ^ plaintext[PUBLICKEY_HEX_BYTES + index];
    }
    if difference != 0 {
        return Ok(SecretKey::WrongPassword);
    }
    let mut key = [0; PUBLICKEY_HEX_BYTES];
    key.copy_from_slice(&plaintext[..PUBLICKEY_HEX_BYTES]);
    Ok(SecretKey::Key(key))
}

#[cfg(test)]
mod tests {
    use super::*;

    const KEY: &[u8; 48] = b"0123456789abcdef0123456789abcdef0123456789abcdef";
    // Independent GLIBC_2.2.5 xencrypt outputs, not generated by this decoder.
    const ENCRYPTED: &[u8; 64] =
        b"c40ca9443dc08c42cf14a8edccd398d43cf91de14e0fcad3cec56c8462334dfb";

    #[test]
    fn gnu_ciphertext_recovers_the_complete_secret() {
        assert_eq!(
            decrypt_secret(ENCRYPTED, b"password"),
            Ok(SecretKey::Key(*KEY))
        );
    }

    #[test]
    fn wrong_password_is_a_found_but_empty_secret() {
        assert_eq!(
            decrypt_secret(ENCRYPTED, b"incorrect"),
            Ok(SecretKey::WrongPassword)
        );
    }

    #[test]
    fn valid_encryption_with_bad_checksum_does_not_publish_a_key() {
        let bad = b"c40ca9443dc08c42cf14a8edccd398d43cf91de14e0fcad3912202360a113a0f";
        assert_eq!(
            decrypt_secret(bad, b"password"),
            Ok(SecretKey::WrongPassword)
        );
    }

    #[test]
    fn empty_and_long_passwords_follow_the_legacy_key_derivation() {
        let empty = b"617b3a0ce8f0710031e2ac867f397b3b95f5d1ab71069e3a9bda0cd3626c56f4";
        assert_eq!(decrypt_secret(empty, b""), Ok(SecretKey::Key(*KEY)));
        assert_eq!(
            decrypt_secret(ENCRYPTED, b"password-tail"),
            Ok(SecretKey::Key(*KEY))
        );
    }

    #[test]
    fn records_preserve_exact_identity_and_accept_comments_and_hex_case() {
        let encrypted = std::str::from_utf8(ENCRYPTED).unwrap().to_ascii_uppercase();
        let public = std::str::from_utf8(KEY).unwrap();
        let image = format!("# keys\n unix.7@domain\t{public}:{encrypted} # key\n");
        let found = lookup_encrypted_secret(image.as_bytes(), b"unix.7@domain").unwrap();
        assert_eq!(
            decrypt_secret(&found, b"password"),
            Ok(SecretKey::Key(*KEY))
        );
        assert_eq!(
            lookup_encrypted_secret(image.as_bytes(), b"unix.7@Domain"),
            None
        );
        assert_eq!(
            lookup_encrypted_secret(image.as_bytes(), b"unix.7@other"),
            None
        );
    }

    #[test]
    fn first_matching_record_remains_authoritative() {
        let image = format!(
            "user broken\nuser {}:{}\n",
            std::str::from_utf8(KEY).unwrap(),
            std::str::from_utf8(ENCRYPTED).unwrap()
        );
        assert_eq!(lookup_encrypted_secret(image.as_bytes(), b"user"), None);
    }

    #[test]
    fn malformed_or_incomplete_secret_material_is_rejected() {
        let public = std::str::from_utf8(KEY).unwrap();
        for length in [0, 1, 16, 32, 48, 63, 65, 128] {
            let image = format!("user {public}:{}\n", "a".repeat(length));
            assert_eq!(lookup_encrypted_secret(image.as_bytes(), b"user"), None);
        }
        for invalid in [b'z', b':', 0, b' '] {
            let mut encrypted = *ENCRYPTED;
            encrypted[31] = invalid;
            let mut image = format!("user {public}:").into_bytes();
            image.extend_from_slice(&encrypted);
            assert_eq!(lookup_encrypted_secret(&image, b"user"), None);
        }
    }
}
